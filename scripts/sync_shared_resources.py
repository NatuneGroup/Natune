#!/usr/bin/env python3
"""Copies the Android app resources that shared code uses into :shared-ui's compose resources.

app/src/main/res stays the single source of strings (and their Weblate translations), drawables and
fonts. When a file moves from :app into a shared module, its R.string.x / R.drawable.x references
become Res.string.x / Res.drawable.x; this script finds every such name that :shared-ui does not
define by hand and generates it from the app resources:

- strings and plurals, in every locale the app translates, into values*/app_strings.xml;
- drawables and fonts, copied file for file, recorded in app-resources.json so they can be pruned.

A shared name that differs from an app name it collides with is referenced as app_<name> and generated
from <name>. Compose Multiplatform formats only positional arguments, so a string that takes them has
its Android %% escape turned into a plain %.

    python3 scripts/sync_shared_resources.py           # write
    python3 scripts/sync_shared_resources.py --check   # exit 1 when out of date
"""

from __future__ import annotations

import json
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
APP_RES = Path("app/src/main/res")
SHARED_RES = Path("shared-ui/src/commonMain/composeResources")
SHARED_SOURCES = (Path("shared-ui/src"), Path("desktopApp/src"))
GENERATED_STRINGS = "app_strings.xml"
MANIFEST = Path("shared-ui/app-resources.json")
PREFIX = "app_"
HEADER = (
    "<!-- Generated by scripts/sync_shared_resources.py from app/src/main/res. "
    "Edit the app resources and rerun the script; do not edit this file. -->\n"
)

REFERENCE = re.compile(r"\bRes\.(string|plurals|drawable|font)\.(\w+)")
ELEMENT = re.compile(r'(<(string|plurals)\s+name="([^"]+)"[^>]*>.*?</\2>)', re.S)
POSITIONAL = re.compile(r"%\d+\$")
FILE_KINDS = {"drawable": ("drawable", (".xml", ".png", ".webp", ".jpg", ".svg")), "font": ("font", (".ttf", ".otf", ".xml"))}


def referenced_names(root: Path) -> dict[str, set[str]]:
    names: dict[str, set[str]] = {"string": set(), "plurals": set(), "drawable": set(), "font": set()}
    for base in SHARED_SOURCES:
        for path in sorted((root / base).rglob("*.kt")):
            for kind, name in REFERENCE.findall(path.read_text(encoding="utf-8", errors="ignore")):
                names[kind].add(name)
    return names


def hand_written(root: Path, generated_files: set[str]) -> dict[str, set[str]]:
    """Every resource :shared-ui defines itself, in any source set (iosMain carries its own)."""
    names: dict[str, set[str]] = {"string": set(), "plurals": set(), "drawable": set(), "font": set()}
    for shared in sorted((root / "shared-ui/src").glob("*/composeResources")):
        for path in sorted(shared.glob("values*/*.xml")):
            if path.name == GENERATED_STRINGS:
                continue
            for _, kind, name in ELEMENT.findall(path.read_text(encoding="utf-8")):
                names[kind].add(name)
        for kind, (folder, _) in FILE_KINDS.items():
            for path in sorted(shared.glob(f"{folder}*/*")):
                if path.relative_to(root).as_posix() not in generated_files:
                    names[kind].add(path.stem)
    return names


def app_elements(root: Path) -> dict[str, dict[str, str]]:
    """Locale directory name -> resource name -> raw XML element, from every app values*/ folder."""
    out: dict[str, dict[str, str]] = {}
    for directory in sorted((root / APP_RES).glob("values*")):
        entries: dict[str, str] = {}
        for path in sorted(directory.glob("*.xml")):
            for element, _, name in ELEMENT.findall(path.read_text(encoding="utf-8")):
                entries[name] = element
        if entries:
            out[directory.name] = entries
    return out


def source_name(name: str, app_names: set[str]) -> str | None:
    if name in app_names:
        return name
    if name.startswith(PREFIX) and name[len(PREFIX):] in app_names:
        return name[len(PREFIX):]
    return None


def convert(element: str, name: str, source: str) -> str:
    element = element.replace(f'name="{source}"', f'name="{name}"', 1)
    if POSITIONAL.search(element):
        element = element.replace("%%", "%")
    return element


def plan(root: Path = ROOT) -> tuple[dict[str, str], dict[str, str], list[str]]:
    """Returns (generated text files, copied files dst->src, problems), paths relative to root."""
    manifest_path = root / MANIFEST
    previous = set(json.loads(manifest_path.read_text())) if manifest_path.is_file() else set()
    wanted = referenced_names(root)
    own = hand_written(root, previous)
    locales = app_elements(root)
    base = locales.get("values", {})
    texts: dict[str, str] = {}
    copies: dict[str, str] = {}
    problems: list[str] = []

    string_names = sorted((wanted["string"] | wanted["plurals"]) - own["string"] - own["plurals"])
    by_locale: dict[str, list[str]] = {}
    for name in string_names:
        source = source_name(name, set(base))
        if source is None:
            problems.append(f"Res.string.{name} is defined neither in :shared-ui nor in app/src/main/res")
            continue
        for directory, entries in locales.items():
            if source in entries:
                by_locale.setdefault(directory, []).append(convert(entries[source], name, source))
    for directory, elements in sorted(by_locale.items()):
        body = "\n".join(f"    {element}" for element in elements)
        texts[(SHARED_RES / directory / GENERATED_STRINGS).as_posix()] = (
            f'<?xml version="1.0" encoding="utf-8"?>\n{HEADER}<resources>\n{body}\n</resources>\n'
        )

    for kind, (folder, extensions) in FILE_KINDS.items():
        for name in sorted(wanted[kind] - own[kind]):
            source = name[len(PREFIX):] if name.startswith(PREFIX) else name
            found = [
                path
                for path in sorted((root / APP_RES).glob(f"{folder}*/{source}.*"))
                if path.suffix in extensions
            ]
            if not found:
                problems.append(f"Res.{kind}.{name} is defined neither in :shared-ui nor in app/src/main/res")
            for path in found:
                destination = SHARED_RES / path.parent.name / f"{name}{path.suffix}"
                copies[destination.as_posix()] = path.relative_to(root).as_posix()
    return texts, copies, problems


def current_generated(root: Path) -> set[str]:
    manifest_path = root / MANIFEST
    files = set(json.loads(manifest_path.read_text())) if manifest_path.is_file() else set()
    files.update(path.relative_to(root).as_posix() for path in (root / SHARED_RES).glob(f"values*/{GENERATED_STRINGS}"))
    return files


def problems(root: Path = ROOT) -> list[str]:
    """What --check reports: missing definitions plus any generated file that is stale or orphaned."""
    texts, copies, found = plan(root)
    expected = set(texts) | set(copies)
    for path, text in texts.items():
        if not (root / path).is_file() or (root / path).read_text(encoding="utf-8") != text:
            found.append(f"{path} is stale")
    for path, source in copies.items():
        if not (root / path).is_file() or (root / path).read_bytes() != (root / source).read_bytes():
            found.append(f"{path} is stale")
    for path in sorted(current_generated(root) - expected):
        found.append(f"{path} is no longer referenced")
    manifest = sorted(copies)
    if manifest and (not (root / MANIFEST).is_file() or json.loads((root / MANIFEST).read_text()) != manifest):
        found.append(f"{MANIFEST.as_posix()} is stale")
    if not manifest and (root / MANIFEST).is_file():
        found.append(f"{MANIFEST.as_posix()} is no longer needed")
    return found


def write(root: Path = ROOT) -> list[str]:
    texts, copies, found = plan(root)
    for path in sorted(current_generated(root) - set(texts) - set(copies)):
        (root / path).unlink(missing_ok=True)
    for path, text in texts.items():
        (root / path).parent.mkdir(parents=True, exist_ok=True)
        (root / path).write_text(text, encoding="utf-8")
    for path, source in copies.items():
        (root / path).parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(root / source, root / path)
    if copies:
        (root / MANIFEST).write_text(json.dumps(sorted(copies), indent=1) + "\n")
    elif (root / MANIFEST).is_file():
        (root / MANIFEST).unlink()
    return found


def main(argv: list[str]) -> int:
    found = problems() if "--check" in argv else write()
    for problem in found:
        print(problem)
    return 1 if found else 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
