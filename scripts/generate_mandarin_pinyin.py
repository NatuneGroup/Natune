#!/usr/bin/env python3
"""Generates shared-domain's bundled Mandarin pinyin table (MandarinPinyinData.kt).

Usage:
    python3 scripts/generate_mandarin_pinyin.py <pinyin.txt> <phrases.txt> <out.kt>

Inputs are the text dumps of mozillazg/pinyin-data and mozillazg/phrase-pinyin-data
(both MIT-licensed, see docs/CREDITS.md): kMandarin readings per codepoint and a
per-phrase reading list that corrects polyphonic characters inside common words.
Only phrases whose reading differs from the per-character first-reading join are
kept; the matcher therefore needs a single dictionary lookup plus the cell table.
"""

import sys

CELL_CHUNK = 8000
PHRASE_CHUNK = 8000


def parse_chars(path):
    """pinyin-data format: `U+4E2D: zhōng,zhòng  # 中` — keep the first reading."""
    out = {}
    for line in open(path, encoding="utf-8"):
        line = line.strip()
        if not line.startswith("U+"):
            continue
        cp_text, rest = line.split(":", 1)
        syllables = rest.split("#")[0].strip().split(",")
        cp = int(cp_text[2:], 16)
        if cp > 0xFFFF:
            continue  # Supplementary planes stay uncovered and fall back to ICU.
        out[cp] = syllables[0].strip()
    return out


def parse_phrases(path):
    """phrase-pinyin-data format: `音乐: yīn yuè` (tab-free, first colon splits)."""
    out = {}
    for line in open(path, encoding="utf-8"):
        line = line.strip()
        if not line or line.startswith("#") or ":" not in line:
            continue
        key, _, reading = line.partition(":")
        key = key.strip()
        reading = reading.strip()
        if len(key) >= 2 and key and reading:
            out[key] = " ".join(reading.split())
    return out


def kt_escape(s):
    return (
        s.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\t", "\\t")
        .replace("\n", "\\n")
    )


def chunks(seq, n):
    return [seq[i : i + n] for i in range(0, len(seq), n)]


def main():
    char_path, phrase_path, out_path = sys.argv[1:4]
    chars = parse_chars(char_path)
    base = min(chars)
    top = max(chars) + 1

    syllable_index = {}
    for cp in sorted(chars):
        syl = chars[cp]
        if syl not in syllable_index:
            syllable_index[syl] = len(syllable_index)
    syllables = sorted(syllable_index, key=syllable_index.get)
    assert len(syllables) < 0xFFFF

    cells = []
    for cp in range(base, top):
        syl = chars.get(cp)
        cells.append(chr(syllable_index[syl] if syl is not None else 0xFFFF))

    def naive_reading(key):
        parts = []
        for ch in key:
            cp = ord(ch)
            syl = chars.get(cp)
            parts.append(syl if syl is not None else ch)
        return " ".join(parts)

    phrases = parse_phrases(phrase_path)
    kept = {}
    for key, reading in sorted(phrases.items()):
        if not all(ord(c) <= 0xFFFF for c in key):
            continue
        if reading != naive_reading(key):
            kept[key] = reading
    max_len = max(len(k) for k in kept)

    cell_chunks = chunks(cells, CELL_CHUNK)
    phrase_lines = "".join(f"{k}\t{v}\n" for k, v in kept.items())
    phrase_chunks = chunks(phrase_lines, PHRASE_CHUNK)

    lines = []
    lines.append("// GENERATED by scripts/generate_mandarin_pinyin.py - do not edit by hand.")
    lines.append("// Data: mozillazg/pinyin-data + mozillazg/phrase-pinyin-data (MIT) - docs/CREDITS.md.")
    lines.append("package moe.rukamori.archivetune.shared.domain.lyrics.romanization")
    lines.append("")
    lines.append("/**")
    lines.append(f" * {len(chars)} covered BMP codepoints and {len(kept)} polyphonic phrase overrides,")
    lines.append(" * bundled as packed strings so the runtime table builds with no I/O. The chunks stay")
    lines.append(" * non-const on purpose: a `const` concatenation folds into one literal at compile time,")
    lines.append(" * and the merged cells/phrases strings exceed the 64 KiB modified-UTF-8 limit a class")
    lines.append(" * file constant can hold, so they assemble lazily at first use instead.")
    lines.append(" * Cells are a 16-bit syllable index per codepoint in [BASE_CODEPOINT, BASE_CODEPOINT +")
    lines.append(" * CELLS length); 0xFFFF marks an uncovered slot. Phrases are `key<TAB>reading\\n` rows.")
    lines.append(" */")
    lines.append("internal object MandarinPinyinData {")
    lines.append(f"    const val BASE_CODEPOINT = 0x{base:04X}")
    lines.append(f"    const val MAX_PHRASE_LENGTH = {max_len}")
    # Keep the chunk vals non-const: `const` folds the lazy concatenation into a single
    # literal, and the merged strings exceed the 64 KiB class-file string limit.
    lines.append(f'    private val SYLLABLES = "{kt_escape(" ".join(syllables))}"')
    for i, chunk in enumerate(cell_chunks):
        esc = "".join(f"\\u{ord(c):04X}" for c in chunk)
        lines.append(f'    private val CELLS_{i} = "{esc}"')
    for i, chunk in enumerate(phrase_chunks):
        lines.append(f'    private val PHRASES_{i} = "{kt_escape(chunk)}"')
    lines.append("")
    lines.append("    internal val syllables: List<String> by lazy { SYLLABLES.split(' ') }")
    lines.append(
        "    internal val cells: String by lazy { " + " + ".join(f"CELLS_{i}" for i in range(len(cell_chunks))) + " }"
    )
    lines.append(
        "    internal val phrases: String by lazy { " + " + ".join(f"PHRASES_{i}" for i in range(len(phrase_chunks))) + " }"
    )
    lines.append("}")
    lines.append("")

    with open(out_path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print(f"{len(chars)} chars, {len(syllables)} syllables, {len(kept)} phrases, "
          f"cells [{base:#x},{top:#x}) -> {out_path}")


if __name__ == "__main__":
    main()
