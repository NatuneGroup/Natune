/** Synthetic Java fixtures written by the REAL retained serialization classes, not a user's files. */
class LegacyQueueCompatibilityTest {
    private fun fixture(data: QueueData? = null, type: QueueType = QueueType.LIST): PersistQueue {
        val metadata = MediaMetadata("duplicate", "日本語 👩‍👩‍👦 हंस\u0000", listOf(
            MediaMetadata.Artist(null, "Artist 1", "https://image.invalid/1"),
            MediaMetadata.Artist("artist-2", "Artist 2", null)), -1, "https://image.invalid/cover",
            MediaMetadata.Album("album", "Album"), "set-a", "spotify-id", true, true,
            LocalDateTime.of(2026, 10, 1, 2, 3, 4, 123456789),
            LocalDateTime.of(2025, 1, 2, 3, 4), true, true, "SYNTHETIC-ISRC", "Fixture listener")
        return PersistQueue("Fixture", listOf(metadata, metadata.copy(setVideoId = "set-b")), 1, 12345, type, data,
            listOf(1, 0), listOf(null, 1))
    }
    private fun write(value: Serializable): ByteArray = ByteArrayOutputStream().also {
        PlaybackPersistenceCodec.write(it, value)
    }.toByteArray()
    private fun assertRetainedValues(original: PersistQueue, document: LegacyQueueDocument) {
        val decoded = PlaybackPersistenceCodec.read(document.originalBytes().inputStream()) as PersistQueue
        assertEquals(original.queueType.javaClass, decoded.queueType.javaClass)
        // Retained Kotlin object classes have no readResolve: legacy Java decoding creates a new
        // instance. QueueExt correctly dispatches by `is`, not singleton reference equality.
        assertEquals(original, decoded.copy(queueType = original.queueType))
    }

    @Test fun retainedMetadataAndEveryRadioVariantRoundTripWithoutProjection() {
        val variants = listOf(
            null to QueueType.LIST,
            QueueData.YouTubeData("video", "RDmix", "params", true) to QueueType.YOUTUBE,
            QueueData.YouTubeAlbumRadioData("playlist", 12, "continuation", true) to QueueType.YOUTUBE_ALBUM_RADIO,
            QueueData.LocalAlbumRadioData("album", 3, "playlist", "tail", true) to QueueType.LOCAL_ALBUM_RADIO,
        )
        for ((data, type) in variants) {
            val original = fixture(data, type)
            val bytes = write(original)
            val doc = LegacyJavaQueueReader().read(bytes)
            assertContentEquals(bytes, doc.originalBytes())
            // Trusted locally generated bytes only: real legacy reader independently checks exact full values.
            assertRetainedValues(original, doc)
            val access = LegacyQueueAccess(doc)
            assertEquals(2, access.items().size)
            assertEquals("set-a", doc.text(access.field(access.items()[0], "setVideoId")))
            assertEquals("set-b", doc.text(access.field(access.items()[1], "setVideoId")))
            val serializedFields = ObjectStreamClass.lookup(MediaMetadata::class.java).fields.map { it.name }.toSet()
            assertEquals(serializedFields, access.items()[0].fields.keys.map { it.substringAfterLast('#') }.toSet())
            assertEquals(1L, ObjectStreamClass.lookup(PersistQueue::class.java).serialVersionUID)
        }
    }
    @Test fun finiteContinuationConsumedTokensManualOccurrencesAndShuffleSurvive() {
        val base = fixture()
        val snapshot = FinitePlaylistSnapshot("Finite", listOf(
            FinitePlaylistEntry(base.items[0], "occurrence-a", 0),
            FinitePlaylistEntry(base.items[1], "occurrence-b", 4)), "next-token",
            FinitePlaylistPhase.PAGEABLE, linkedSetOf("already-a", "already-b"))
        val original = base.copy(queueType = QueueType.YOUTUBE_PLAYLIST,
            queueData = QueueData.YouTubePlaylistData("PLfixture", "video", "params", 4, "set-b",
                snapshot, listOf("occurrence-a", null), true))
        val doc = LegacyJavaQueueReader().read(write(original))
        assertRetainedValues(original, doc)
        val access = LegacyQueueAccess(doc)
        val data = doc.objectNode(access.field(access.queue, "queueData"))
        val saved = doc.objectNode(access.field(data, "snapshot"))
        assertEquals("next-token", doc.text(access.field(saved, "continuation")))
        assertEquals(setOf("already-a", "already-b"), access.collection(access.field(saved, "consumedTokens")).map(doc::text).toSet())
        assertEquals(listOf("occurrence-a", null), access.collection(access.field(data, "timelineOccurrences")).map(doc::text))
        assertEquals("PAGEABLE", (doc.node(access.field(saved, "phase")) as LegacyNode.Enum).name)
    }
    @Test fun passiveReaderPreservesAnUnrecognizedFieldAndNeverInvokesReadObject() {
        val bytes = write(fixture())
        val needle = "suggestedBy".encodeToByteArray()
        val index = bytes.indices.first { i -> i + needle.size <= bytes.size && bytes.copyOfRange(i, i + needle.size).contentEquals(needle) }
        "newFieldXYZ".encodeToByteArray().copyInto(bytes, index)
        val doc = LegacyJavaQueueReader().read(bytes)
        assertTrue(LegacyQueueAccess(doc).items()[0].fields.keys.any { it.endsWith("#newFieldXYZ") })
        assertContentEquals(bytes, doc.originalBytes())
        Hook.called = false
        assertFailsWith<IllegalArgumentException> { LegacyJavaQueueReader().read(write(Hook())) }
        assertFalse(Hook.called)
    }
    private class Hook : Serializable {
        @Suppress("UNUSED_PARAMETER")
        private fun readObject(input: ObjectInputStream) { called = true }
        companion object { var called = false }
    }
    @Test fun rejectsTruncationTrailingObjectsCyclesAndUnsupportedVersions() {
        val bytes = write(fixture())
        assertFailsWith<IllegalArgumentException> { LegacyJavaQueueReader().read(bytes.copyOf(bytes.size - 1)) }
        assertFailsWith<IllegalArgumentException> { LegacyJavaQueueReader().read(bytes + byteArrayOf(0x70)) }
        val changed = bytes.copyOf()
        val uidEnd = 8 + "moe.rukamori.archivetune.models.PersistQueue".length + 7
        changed[uidEnd] = 99
        assertFailsWith<IllegalArgumentException> { LegacyJavaQueueReader().read(changed) }
        val cyclic = mutableListOf<MediaMetadata>()
        @Suppress("UNCHECKED_CAST")
        (cyclic as MutableList<Any>).add(cyclic)
        assertFailsWith<IllegalArgumentException> { LegacyJavaQueueReader().read(write(fixture().copy(items = cyclic))) }
    }
    @Test fun diskEnvelopeReopenCasAndStaleDuplicateTicksRetainExactSourceBytes() = runTest {
        val root = Files.createTempDirectory("legacy-envelope-test")
        try {
            val bytes = write(fixture())
            val store = JvmLosslessQueueStore(root)
            assertTrue(store.write(7, bytes, null))
            assertFalse(store.write(8, bytes, null))
            assertFalse(store.updatePosition(7, 0, 100))
            assertTrue(store.updatePosition(7, 1, 9000))
            assertEquals(9000L, JvmLosslessQueueStore(root).read()!!.positionMs)
            assertContentEquals(bytes, store.read()!!.document.originalBytes())
            val results = coroutineScope { List(5) { async { JvmLosslessQueueStore(root).write(8, bytes, 7) } }.awaitAll() }
            assertEquals(1, results.count { it })
            assertFalse(store.updatePosition(7, 1, 10))
            assertEquals(12345L, store.read()!!.positionMs)
            assertTrue(store.write(9, write(fixture().copy(mediaItemIndex = -1)), 8))
            assertFalse(store.updatePosition(9, -1, 10))
            Files.writeString(root.resolve("legacy-queue.json"), """{"version":99}""")
            assertFailsWith<IllegalArgumentException> { store.write(10, bytes, 9) }
            assertEquals("""{"version":99}""", Files.readString(root.resolve("legacy-queue.json")))
        } finally { root.toFile().deleteRecursively() }
    }
}
